-- =====================================================================
-- EKSPORT STRUKTUR DATABASE (baca sahaja — tidak mengubah apa-apa)
-- =====================================================================
-- Hasilkan SATU skrip SQL yang membina semula struktur database Portal LPP:
-- jenis enum, jadual, kekangan, indeks, view, fungsi, trigger, RLS, polisi,
-- dan bucket storage berserta polisinya. TIADA data disertakan.
--
-- Cara guna (Supabase):
--   1. SQL Editor → New query → tampal fail ini → Run.
--   2. Hasil: satu baris, satu lajur "schema_sql". Klik sel → salin, atau
--      Export → Download CSV.
--   3. Simpan dalam repo sebagai schema-snapshot-<tarikh>.sql.
-- Run semula bila-bila masa (cth selepas setiap migration) untuk snapshot baru.
--
-- Untuk PostgreSQL bukan Supabase: skrip memerlukan peranan "anon" &
-- "authenticated" & "service_role", skema "auth" dengan jadual auth.users dan fungsi
-- auth.uid(), serta skema "storage". Lihat bahagian pertama hasil eksport.
-- =====================================================================

with
fn as (  -- fungsi milik kita (bukan dari extension)
  select p.oid, p.proname
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f','p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
tbl as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r','p')
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
parts as (
  -- 0. Pengepala
  select 0 as grp, '' as k, format(
$h$-- Snapshot struktur database Portal LPP
-- Dijana: %s  ·  PostgreSQL %s
-- Bina semula: run fail ini dalam database kosong (Supabase: SQL Editor).
-- Bukan Supabase: sediakan dahulu peranan anon/authenticated/service_role, skema auth
-- (auth.users, auth.uid()) dan skema storage (buckets, objects).

-- Fungsi mungkin merujuk fungsi lain yang dicipta kemudian (susunan abjad);
-- sama seperti pg_dump, jangan semak isi fungsi semasa mencipta.
set check_function_bodies = off;$h$,
    to_char(now() at time zone 'Asia/Kuching', 'YYYY-MM-DD HH24:MI "MYT"'),
    current_setting('server_version')) as sql

  -- 1. Extension yang digunakan
  union all
  -- Sebagai nota sahaja: Supabase memasang banyak extension sendiri (pg_graphql,
  -- vault, ...) yang tiada di PostgreSQL biasa. Pasang yang benar-benar perlu.
  select 1, e.extname, format('-- %s %s', e.extname, e.extversion)
  from pg_extension e
  where e.extname not in ('plpgsql')

  -- 2. Jenis enum
  union all
  select 2, t.typname, format('do $$ begin create§ type public.%I as enum (%s); exception when duplicate_object then null; end $$;',
    t.typname, string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder))
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public'
  group by t.typname

  -- 3. Sequence bebas (bukan identity)
  union all
  select 3, c.relname, format('create§ sequence if not exists public.%I;', c.relname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')

  -- 4. Jadual (lajur, jenis, default, not null)
  union all
  select 4, t.relname, format(E'create§ table if not exists public.%I (\n  %s\n);', t.relname,
    string_agg(
      quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
      || case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end
      || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
              when ad.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end
      || case when a.attnotnull then ' not null' else '' end,
      E',\n  ' order by a.attnum))
  from tbl t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = t.oid and ad.adnum = a.attnum
  group by t.relname

  -- 5. Kekangan selain foreign key (primary key, unique, check)
  union all
  select 5, t.relname || '.' || co.conname, format('alter§ table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from tbl t join pg_constraint co on co.conrelid = t.oid
  where co.contype in ('p','u','c','x')

  -- 6. Foreign key (selepas semua jadual wujud)
  union all
  select 6, t.relname || '.' || co.conname, format('alter§ table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from tbl t join pg_constraint co on co.conrelid = t.oid
  where co.contype = 'f'

  -- 7. Indeks (yang bukan di belakang kekangan)
  union all
  select 7, i.indexname, i.indexdef || ';'
  from pg_indexes i
  where i.schemaname = 'public' and i.tablename in (select relname from tbl)
    and not exists (select 1 from pg_constraint co join pg_class ic on ic.oid = co.conindid where ic.relname = i.indexname)

  -- 8. Fungsi & prosedur
  union all
  select 8, f.proname || '(' || pg_get_function_identity_arguments(f.oid) || ')', pg_get_functiondef(f.oid) || ';'
  from fn f

  -- 9. View
  union all
  select 9, c.relname, format(E'create§ or replace view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid, true))
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'

  -- 10. Trigger
  union all
  select 10, t.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid, true) || ';'
  from tbl t join pg_trigger tg on tg.tgrelid = t.oid
  where not tg.tgisinternal

  -- 11. Row Level Security
  union all
  select 11, t.relname, format('alter§ table public.%I enable row level security;', t.relname)
    || case when t.relforcerowsecurity then format(' alter§ table public.%I force row level security;', t.relname) else '' end
  from tbl t where t.relrowsecurity

  -- 12. Polisi RLS (public & storage)
  union all
  select 12, p.schemaname || '.' || p.tablename || '.' || p.policyname,
    format('create§ policy %I on %I.%I as %s for %s to %s%s%s;',
      p.policyname, p.schemaname, p.tablename, lower(p.permissive), lower(p.cmd),
      (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ') from unnest(p.roles) r),
      case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
      case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
  from pg_policies p
  where p.schemaname = 'public'
     or (p.schemaname = 'storage' and p.tablename = 'objects')

  -- 14. Kebenaran jadual untuk peranan app (Supabase beri secara automatik;
  --     PostgreSQL biasa perlukannya).
  union all
  select 14, g.table_name || '.' || g.grantee,
    format('grant§ %s on public.%I to %I;', string_agg(distinct g.privilege_type, ', '), g.table_name, g.grantee)
  from information_schema.role_table_grants g
  where g.table_schema = 'public' and g.grantee in ('anon','authenticated','service_role')
    and g.table_name in (select relname from tbl)
  group by g.table_name, g.grantee
  union all
  select 14, '~schema', 'grant§ usage on schema public to anon, authenticated;'

  -- 13. Bucket storage
  union all
  select 13, b.id, format('insert§ into storage.buckets (id, name, public) values (%L, %L, %s) on conflict (id) do nothing;', b.id, b.name, case when b.public then 'true' else 'false' end)
  from storage.buckets b
)
-- "§" memecahkan kata kunci SQL dalam teks hasil (cth "create§ table") supaya
-- pengimbas keselamatan SQL Editor Supabase tidak menyangka query ini mencipta
-- jadual. Ia dibuang di sini; query ini hanya MEMBACA.
select replace(string_agg(
  case when grp > 0 and prev is distinct from grp then
    E'-- ---------------------------------------------------------------------\n-- '
    || (array['Extension yang dipasang (nota)','Jenis enum','Sequence','Jadual','Kekangan','Foreign key','Indeks',
              'Fungsi','View','Trigger','Row Level Security','Polisi RLS','Bucket storage','Kebenaran (grant)'])[grp]
    || E'\n-- ---------------------------------------------------------------------\n'
  else '' end || sql,
  E'\n\n' order by grp, k), '§', '') as schema_sql
from (select grp, k, sql, lag(grp) over (order by grp, k) as prev from parts) x;
